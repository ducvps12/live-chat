import fs from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';
import tailwindcss from '@tailwindcss/postcss';

const projectRoot = process.cwd();
const sourcePath = path.join(projectRoot, 'src', 'styles', 'globals.css');
const outputPath = path.join(projectRoot, 'public', 'app.css');
const temporaryPath = `${outputPath}.tmp`;

const source = await fs.readFile(sourcePath, 'utf8');
const result = await postcss([tailwindcss()]).process(source, {
  from: sourcePath,
  to: outputPath,
  map: false,
});

const banner = '/* Generated by scripts/build-global-css.mjs. Do not edit directly. */\n';
await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(temporaryPath, `${banner}${result.css}`, 'utf8');
await fs.rename(temporaryPath, outputPath);

console.log(`Built public/app.css (${Buffer.byteLength(result.css)} bytes)`);
